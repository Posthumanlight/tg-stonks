// Generate src/protocol/index.ts from the server's Pydantic models.
// Pydantic -> JSON Schema (server/app/cli/export_schema.py) -> json-schema-to-typescript.
// Usage: npm run gen:protocol            (write)
//        npm run gen:protocol -- --check (exit 1 if the committed file is stale)
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const outFile = fileURLToPath(new URL("../src/protocol/index.ts", import.meta.url));
const check = process.argv.includes("--check");

const schema = JSON.parse(
  execSync("poetry run python server/app/cli/export_schema.py", {
    cwd: repoRoot,
    encoding: "utf8",
  }),
);
const version = schema["x-protocol-version"];
const defs = schema.$defs ?? {};

// Pydantic titles every property ("Index", "Name"...), which would make
// json-schema-to-typescript emit a named alias per field. Keep only model titles.
for (const def of Object.values(defs)) {
  for (const prop of Object.values(def.properties ?? {})) delete prop.title;
}

const names = Object.keys(defs).sort();
const root = {
  title: "ProtocolModels",
  description: "Registry of every protocol model (codegen root; not a message).",
  type: "object",
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
  required: names,
  additionalProperties: false,
  $defs: defs,
};

const body = await compile(root, "ProtocolModels", {
  bannerComment:
    "/* GENERATED by scripts/gen-protocol.mjs from server/app/protocol. Do not edit. */",
  additionalProperties: false,
  strictIndexSignatures: true,
});
const output = `${body}\nexport const PROTOCOL_VERSION = ${version};\n`;

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== output) {
    console.error("src/protocol/index.ts is stale: run `npm run gen:protocol`.");
    process.exit(1);
  }
  console.log("protocol types are up to date");
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, output);
  console.log(`wrote ${outFile} (PROTOCOL_VERSION ${version}, ${names.length} models)`);
}
